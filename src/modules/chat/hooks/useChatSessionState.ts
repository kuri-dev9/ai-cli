/**
 * 따라가기를 놓는 거리와 다시 붙는 거리.
 *
 * 두 값이 달라야 한다. 하나였을 때는 그 선을 스치기만 해도 다시 붙었고,
 * 답이 자라는 동안에는 바닥이 계속 내려가므로 사용자가 읽으려고 멈춘 자리가
 * 자꾸 그 선 안으로 들어왔다. 내려오는 길에 우연히 가까워진 것과 바닥까지
 * 내려간 것은 다른 의도다.
 *
 * 놓을 때는 넉넉하게(50px) — 한 줄 늘어났다고 놓아 버리면 안 된다.
 * 다시 붙을 때는 인색하게(8px) — 진짜 바닥에 닿았을 때만 붙는다. 그래도
 * 붙이고 싶으면 바닥으로 가는 버튼이 따로 있다.
 */
const DETACH_FROM_BOTTOM_PX = 50;
const REATTACH_TO_BOTTOM_PX = 8;

/**
 * 방향이 있는 스크롤 입력(휠 deltaY, 터치 이동량)을 의도로 읽는다.
 *
 * 위로 올리는 것은 그 자체로 결론이다 — 어디에 있든 따라가기를 놓는다.
 * `scroll` 이벤트까지 기다리면 그 사이 ResizeObserver 가 바닥으로 도로
 * 끌어내려서, 트랙패드처럼 몇 px 씩 올리는 입력은 영영 빠져나가지 못한다.
 *
 * 아래로 내리는 것은 여기서 판정하지 않는다. 바닥에 닿았는지는 그 입력이
 * 스크롤에 반영된 뒤에야 알 수 있으므로 `resolveScrolledUpAfterScroll` 이 맡는다.
 */
export function resolveFollowIntent(deltaY: number): 'release' | null {
  return deltaY < 0 ? 'release' : null;
}

/** 직전에 확인한 스크롤 위치와 높이. 이번 `scroll` 이 어느 쪽으로 움직였는지 재는 기준. */
export type ScrollSample = { top: number; height: number };

/**
 * `scroll` 이벤트 하나를 보고 따라가기를 놓을지(true) 붙을지(false) 정한다.
 *
 * 거리만으로 판정하면 스트리밍이 끼어든다. 코드 블록이나 도구 카드처럼 큰
 * 덩어리가 한 번에 붙으면 가만히 있어도 바닥과의 거리가 50px 를 넘어서
 * "사용자가 올렸다" 로 읽혔고, 반대로 바닥이 계속 멀어지니 끝까지 내려가도
 * 8px 안에 들기 어려웠다. 그래서 직전 위치(`previous`)와 비교해 실제로
 * 움직인 방향을 함께 본다.
 *
 * - 따라가는 중: 위로 움직였고(내용이 줄어 밀려난 것이 아니고) 바닥에서
 *   50px 이상 멀어졌을 때만 놓는다. 내용이 자라서 생긴 거리는 무시한다.
 * - 놓인 상태: 아래로 움직여서 지금 바닥 8px 안에 닿았을 때만 붙는다.
 *   움직이지 않았거나 위로 움직였으면 그대로 놓아 둔다. 진행 중인 턴은
 *   화면 밖에서도 실제 높이를 유지하므로(LazyMessageRow 의 keepMounted)
 *   여기서 보는 바닥은 진짜 바닥이다.
 *
 * 직전 위치가 없으면(첫 이벤트) 거리만으로 판정한다.
 */
export function resolveScrolledUpAfterScroll({
  wasScrolledUp,
  previous,
  top,
  height,
  clientHeight,
}: {
  wasScrolledUp: boolean;
  previous: ScrollSample | null;
  top: number;
  height: number;
  clientHeight: number;
}): boolean {
  const liveDistance = height - top - clientHeight;
  const movedUp = previous !== null && top < previous.top;

  if (!wasScrolledUp) {
    if (liveDistance < DETACH_FROM_BOTTOM_PX) {
      return false;
    }
    if (previous === null) {
      return true;
    }
    // 내용이 줄면 브라우저가 scrollTop 을 끌어올린다. 사용자가 올린 게 아니다.
    return movedUp && height >= previous.height;
  }

  if (previous === null) {
    return liveDistance > REATTACH_TO_BOTTOM_PX;
  }
  // 아래로 실제로 움직였을 때만 붙는다. 휠을 위로 굴린 직후에는 그 직전에
  // 우리가 바닥으로 내린 것의 `scroll` 이 아직 남아 있다 — 위치는 바닥 그대로라
  // 거리만 보면 "바닥이네" 하고 도로 붙었고, 위로 굴리는 족족 끌려 내려갔다.
  if (top <= previous.top) {
    return true;
  }
  // "직전 바닥까지 닿았는지" 로 붙이던 규칙은 뺐다. 위쪽 줄이 실제 높이로
  // 다시 그려지면 브라우저가 보던 자리를 지키려고 scrollTop 을 늘리는데, 그게
  // 아래로 내린 것처럼 보여 위로 올리는 도중에 최하단으로 끌려갔다.
  return liveDistance > REATTACH_TO_BOTTOM_PX;
}

/**
 * ResizeObserver 가 지켜볼 본문 요소.
 *
 * 메시지가 있으면 스크롤 컨테이너의 첫 자식은 본문이 아니라 내보내기
 * 메뉴(sticky) 래퍼다 — 그걸 관찰하면 스트리밍으로 답이 자라도 아무 일도
 * 일어나지 않아서, 화면이 위에 멈춘 채 메시지 경계에서만 점프했다. 그래서
 * ChatMessagesPane 이 본문 div 에 붙여 둔 표식을 찾는다.
 */
export function findTranscriptContentElement(container: HTMLElement): Element {
  return (
    container.querySelector('[data-chat-scroll-content]')
    ?? container.firstElementChild
    ?? container
  );
}

/**
 * Finds the rendered row for a resolved search target.
 *
 * Only an exact timestamp match counts while retries remain: the widened window
 * may not be committed yet, and accepting the nearest row then would scroll to
 * an arbitrary message and flash the highlight on it — the silent wrong answer
 * this rewrite exists to remove. `allowNearest` is used on the final attempt
 * because a hit on the second or later call of a collapsed tool group has no row
 * of its own; groupConsecutiveTools stamps the group with the run's FIRST
 * timestamp, so the group row is the nearest, not an exact, match.
 */
function findRenderedMessageElement(
  container: HTMLElement,
  timestamp: unknown,
  allowNearest: boolean,
): HTMLElement | null {
  const targetTimestamp = String(timestamp);
  const targetTime = new Date(targetTimestamp).getTime();
  const candidates = container.querySelectorAll<HTMLElement>('[data-message-timestamp]');

  let nearest: HTMLElement | null = null;
  let nearestDistance = Infinity;

  for (const candidate of candidates) {
    const candidateTimestamp = candidate.getAttribute('data-message-timestamp');
    if (!candidateTimestamp) {
      continue;
    }
    if (candidateTimestamp === targetTimestamp) {
      return candidate;
    }

    if (!allowNearest) {
      continue;
    }

    const candidateTime = new Date(candidateTimestamp).getTime();
    if (!Number.isFinite(candidateTime) || !Number.isFinite(targetTime)) {
      continue;
    }

    const distance = Math.abs(candidateTime - targetTime);
    if (distance < nearestDistance) {
      nearestDistance = distance;
      nearest = candidate;
    }
  }

  return nearest;
}
